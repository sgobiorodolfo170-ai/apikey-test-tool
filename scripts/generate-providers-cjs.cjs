// 从 src/data/providers.json 生成主进程可 require 的 CJS 快照。
// 目的：避免 Electron 主进程与渲染层各自维护一份供应商列表。

const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const source = path.join(root, 'src', 'data', 'providers.json')
const outDir = path.join(root, 'electron', 'generated')
const outFile = path.join(outDir, 'providers.cjs')

const data = JSON.parse(fs.readFileSync(source, 'utf8'))
if (!Array.isArray(data.providers) || data.providers.length === 0) {
  throw new Error('providers.json 中没有 providers')
}

const seen = new Set()
for (const provider of data.providers) {
  if (!provider.id || !provider.name || !provider.baseUrl) {
    throw new Error(`providers.json 存在缺少 id/name/baseUrl 的条目：${JSON.stringify(provider)}`)
  }
  if (seen.has(provider.id)) {
    throw new Error(`providers.json 存在重复 id：${provider.id}`)
  }
  seen.add(provider.id)
}

fs.mkdirSync(outDir, { recursive: true })
const content = `// AUTO-GENERATED by scripts/generate-providers-cjs.cjs. Do not edit.
// Source: src/data/providers.json
module.exports = ${JSON.stringify(data, null, 2)}
`
fs.writeFileSync(outFile, content, 'utf8')

const snapshot = require(outFile)
if (snapshot.providers.length !== data.providers.length) {
  throw new Error('生成的 CJS 快照与 providers.json 数量不一致')
}

console.log(
  `[registry] electron/generated/providers.cjs 已生成：${snapshot.providers.length} 个供应商，${snapshot.apiModes.length} 种模式`,
)
